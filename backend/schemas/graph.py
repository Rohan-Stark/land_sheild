from __future__ import annotations

from enum import Enum
from typing import Any

from pydantic import BaseModel, Field


class IntentCategory(str, Enum):
    DOCUMENT_QUESTION = "Document Question"
    PROPERTY_QUESTION = "Property Question"
    LEGAL_GUIDANCE = "Legal Guidance"
    ALERT_QUESTION = "Alert Question"
    INSPECTION_QUESTION = "Inspection Question"
    REPORT_REQUEST = "Report Request"
    GENERAL_KNOWLEDGE = "General Knowledge"
    UNKNOWN = "Unknown"


class ExtractedEntities(BaseModel):
    propertyId: str | None = None
    documentType: str | None = None
    surveyNumber: str | None = None
    khataNumber: str | None = None
    registrationNumber: str | None = None
    inspectionId: str | None = None
    alertId: str | None = None
    dates: list[str] = Field(default_factory=list)
    documentNames: list[str] = Field(default_factory=list)


class GraphRequest(BaseModel):
    """The incoming request to the orchestration graph."""

    requestId: str
    userId: str
    propertyId: str | None = None
    conversationId: str | None = None
    query: str


class ExecutionPlan(BaseModel):
    """The plan generated by the execution planner."""
    
    intent: IntentCategory = IntentCategory.UNKNOWN
    requires_retrieval: bool = False
    requires_tools: bool = False
    required_agents: list[str] = Field(default_factory=list)
    parallel_execution: bool = False
    metadata: dict[str, Any] = Field(default_factory=dict)


class OrchestrationResponse(BaseModel):
    """The final structured response aggregated from agents and tools."""
    
    requestId: str
    intent: IntentCategory
    agent_outputs: dict[str, Any]
    tool_results: dict[str, Any]
    retrieval_results: dict[str, Any]
    confidence_placeholders: dict[str, float]
    errors: list[str]
    metadata: dict[str, Any]
